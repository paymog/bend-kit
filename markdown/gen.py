#!/usr/bin/env python3
"""Write entities.bend: the HTML5 named character references as a balanced search tree."""
from html.entities import html5
from pathlib import Path

HERE = Path(__file__).resolve().parent


def lit(s):
    return '"' + "".join(f"\\u{{{ord(c):X}}}" for c in s) + '"'


def main():
    names = sorted(k[:-1] for k in html5 if k.endswith(";"))
    defs = []

    def node(lo, hi):
        if lo >= hi:
            return "None{}"
        mid = (lo + hi) // 2
        name = f"n{mid}"
        left, right = node(lo, mid), node(mid + 1, hi)
        defs.append(
            f"def {name}.go(c: Cmp, +k: String) -> Maybe<&2, String>:\n"
            f"  match c:\n"
            f"    case LT{{}}:\n      {left if left == 'None{}' else left + '(k)'}\n"
            f"    case EQ{{}}:\n      Some{{{lit(html5[names[mid] + ';'])}}}\n"
            f"    case GT{{}}:\n      {right if right == 'None{}' else right + '(k)'}\n\n"
            f"def {name}(+k: String) -> Maybe<&2, String>:\n"
            f"  {name}.go(String.order(k, {lit(names[mid])}), k)\n"
        )
        return name

    root = node(0, len(names))
    head = "# Generated by gen.py from Python's html.entities.html5. Do not edit.\nimport Base\n\n"
    tail = f"# The text of a named character reference, without its & and ;.\ndef entity(+k: String) -> Maybe<&2, String>:\n  {root}(k)\n"
    (HERE / "entities.bend").write_text(head + "\n".join(defs) + "\n" + tail)
    print(f"{len(names)} entities")


if __name__ == "__main__":
    main()
