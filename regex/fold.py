#!/usr/bin/env python3
# /// script
# requires-python = ">=3.10"
# ///
"""Generate regex/fold.bend: simple case folding orbits, as RE2 and Go use them.

Two code points are equivalent when CaseFolding.txt (statuses C and S) folds
them to the same code point. `others(c)` returns the other members of c's class.

    python3 regex/fold.py      # downloads CaseFolding.txt to regex/ucd/
"""

import pathlib
import urllib.request

VERSION = "17.0.0"
HERE = pathlib.Path(__file__).resolve().parent
UCD = HERE / "ucd"
OUT = HERE / "fold.bend"
MAX = 0x10FFFF


def case_folding():
    path = UCD / "CaseFolding.txt"
    if not path.exists():
        UCD.mkdir(exist_ok=True)
        url = f"https://www.unicode.org/Public/{VERSION}/ucd/CaseFolding.txt"
        urllib.request.urlretrieve(url, path)
    return path.read_text()


def orbits():
    """The other members of each code point's class, for classes of two or more."""
    groups = {}
    for line in case_folding().splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        code, status, mapping = [f.strip() for f in line.split(";")[:3]]
        if status not in ("C", "S"):
            continue
        c, f = int(code, 16), int(mapping, 16)
        groups.setdefault(f, {f}).add(c)
    others = {}
    for members in groups.values():
        for c in members:
            others[c] = sorted(members - {c})
    return others


def segments(others):
    """Cover 0..MAX with (lo, hi, leaf) runs; a leaf is a Bend expression in c."""
    keys = sorted(others)
    out = []
    i = 0
    while i < len(keys):
        c = keys[i]
        os = others[c]
        if len(os) > 1:
            out.append((c, c, "[" + ", ".join(str(o) for o in os) + "]"))
            i += 1
            continue
        # A run of pairs c <-> c+1, c+2 <-> c+3, ...
        n = 0
        while others.get(c + 2 * n) == [c + 2 * n + 1] and others.get(c + 2 * n + 1) == [c + 2 * n]:
            n += 1
        if n >= 2:
            out.append((c, c + 2 * n - 1, f"alt(c, {c})"))
            i += 2 * n
            continue
        # A run with one constant offset.
        d = os[0] - c
        j = i
        while j + 1 < len(keys) and keys[j + 1] == keys[j] + 1 and others[keys[j + 1]] == [keys[j + 1] + d]:
            j += 1
        leaf = f"[(c + {d} : U32)]" if d > 0 else f"[(c - {-d} : U32)]"
        out.append((c, keys[j], leaf))
        i = j + 1
    covered = []
    at = 0
    for lo, hi, leaf in out:
        if at < lo:
            covered.append((at, lo - 1, "Nil{}"))
        covered.append((lo, hi, leaf))
        at = hi + 1
    if at <= MAX:
        covered.append((at, MAX, "Nil{}"))
    return covered


def check(others, segs):
    """Every code point's leaf gives back exactly its others."""
    for lo, hi, leaf in segs:
        for c in range(lo, hi + 1):
            want = others.get(c, [])
            if leaf == "Nil{}":
                got = []
            elif leaf.startswith("alt("):
                got = [c + 1] if (c - lo) % 2 == 0 else [c - 1]
            elif leaf.startswith("[(c + "):
                got = [c + int(leaf[6:].split(" ")[0])]
            elif leaf.startswith("[(c - "):
                got = [c - int(leaf[6:].split(" ")[0])]
            else:
                got = [int(x) for x in leaf[1:-1].split(", ")]
            assert got == want, (hex(c), got, want)


def emit(segs):
    defs = []

    def node(lo, hi):
        # segs[lo..hi] inclusive; return an expression in c.
        if lo == hi:
            return segs[lo][2]
        mid = (lo + hi + 1) // 2
        left, right = node(lo, mid - 1), node(mid, hi)
        name = f"fo.n{len(defs)}"
        defs.append(
            f"def {name}(lt: Bool, +c: U32) -> List<&2, U32>:\n"
            f"  match lt:\n    case True{{}}:\n      {left}\n    case False{{}}:\n      {right}\n"
        )
        return f"{name}(U32.is_lt(c, {segs[mid][0]}), c)"

    root = node(0, len(segs) - 1)
    head = (
        f"# Generated by fold.py from UCD {VERSION} CaseFolding.txt (C and S). Do not edit.\n"
        "import Base\n\n"
        "# c's partner in a run of pairs lo <-> lo+1, lo+2 <-> lo+3, ...\n"
        "def alt(+c: U32, +lo: U32) -> List<&2, U32>:\n"
        "  [Bool.pick(U32, U32.is_eq(U32.mod((c - lo : U32), 2), 0), (c + 1 : U32), (c - 1 : U32))]\n\n"
    )
    tail = (
        "\n# The other code points equivalent to c under simple case folding, ascending.\n"
        f"def others(+c: U32) -> List<&2, U32>:\n  {root}\n"
    )
    return head + "\n".join(defs) + tail


def main():
    others = orbits()
    segs = segments(others)
    check(others, segs)
    OUT.write_text(emit(segs))
    print(f"{len(others)} code points, {len(segs)} segments -> {OUT.name}")


if __name__ == "__main__":
    main()
